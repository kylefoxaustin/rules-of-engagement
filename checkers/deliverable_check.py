def walk(o, path=""):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from walk(v, f"{path}.{k}" if path else k)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from walk(v, f"{path}[{i}]")
    else:
        yield path, o


def numbers_in(text):
    """Decimal numbers that look like measurements, not years/counts/percent-signs."""
    out = set()
    # The lookahead excluded a following DIGIT but not a following LETTER, so a number
    # embedded in a hex token was harvested as data: "52fdb131daa7" (an engine md5) yielded
    # 52, which then failed the md-vs-xlsx agreement check. Any document quoting a hash
    # would trip this. Exclude a following word character too.
    # Strip comma-grouped numbers and identifier-embedded digits BEFORE extraction.
    #   "5,129,336,956 B"  yielded 5 / 129 / 336 / 956 -- four numbers that never existed.
    #   "IQ-9075"          yielded 9075, a part number in a NAME.
    #   "Adreno 663"       yielded 663, a product name.
    # None of these are measurements, and each generated a warning that a reader would have
    # to dismiss by hand -- which is how a warning list becomes noise and stops being read.
    # A MULTIPLIER SUFFIX MUST NOT CHANGE WHETHER A NUMBER IS SEEN. The workbook renders
    # "6.1x" (ASCII x, a word char, which the lookahead below blocks) while the markdown
    # renders "6.1x" with the multiplication sign (not a word char, so it extracts). The
    # SAME claim therefore looked md-only and reported as one-sided drift four times.
    # Detach the suffix first so both spellings parse identically.
    text = re.sub(r"(\d)\s*[x\u00d7](?![\w])", r"\1 ", text)
    text = re.sub(r"\b\d{1,3}(?:,\d{3})+\b", " ", text)          # comma-grouped magnitudes
    text = re.sub(r"\b[A-Za-z]+-?\d+\b", " ", text)              # IQ-9075, T234, sm_110
    # Product names only, and only when the digits are NOT the start of a decimal. Including
    # Orin/Thor here was wrong: they are board names routinely followed by a measurement, so
    # "Orin 0.26%" was stripped as if it were a product number and the floor vanished from
    # the md side of the comparison. A filter that removes real data is worse than the noise
    # it was written to remove.
    text = re.sub(r"\b(?:Adreno|Kryo|Tegra)\s+\d+(?!\.\d)\b", " ", text)  # product names
    # The lookahead blocked ANY following period, so a number ending a sentence -- "IQ-9075
    # 6.3." -- was never extracted, and the same value written mid-sentence elsewhere then
    # looked like one-sided drift. Block a following word char, and block ".<digit>" (a
    # decimal continuation), but allow a bare sentence-ending period.
    for m in re.finditer(r"(?<![\w.])(\d+(?:\.\d+)?)(?!\w|\.\d)", text):
        v = float(m.group(1))
        if v.is_integer() and (1900 <= v <= 2100 or v <= 20):
            continue          # years, section numbers, small counts
        if 0.001 < abs(v) < 1e6:
            out.add(round(v, 4))
    return out


def load_xlsx_text(path):
    try:
        import openpyxl
    except ImportError:
        return None
    wb = openpyxl.load_workbook(path)
    return "\n".join(str(c.value) for ws in wb for row in ws.iter_rows()
                     for c in row if c.value is not None)



