"""DELIVERABLE CHECK — measure twice, cut once.

Three fix-audit cycles on one deliverable produced roughly as many new defects as
they closed. Every one of the new defects had the same cause: **two artifacts,
generated by two mechanisms, patched independently.** A fix landed in the workbook
and not the markdown, or the reverse, and the disagreement shipped.

Reviewing afterwards does not fix that. Review is a cut followed by a measurement.
This runs BEFORE the artifacts are allowed to ship, and it FAILS THE BUILD — so the
measuring happens twice and the cutting happens once.

Checks, each one derived from a defect that actually shipped:

  C1  md and xlsx must agree on every shared number.        (5 disclosures once
      lived only in the workbook; the markdown is the file that gets forwarded)
  C2  no value from a _SUPERSEDED block may appear.         (retracted ceilings)
  C3  no "not measured" claim may name something that IS.   (both files said the
      IQ-9075 fp16 was never measured, on the page containing it)
  C4  a blacklist of phrases known to be wrong.             (they came back twice)
  C5  every number in the deliverable must exist in source. (catches hardcoding,
      which is what let the two files drift apart)
  C6  claimed replicate counts must match the source.       ("median of 3" where
      the source holds 2)

Exit non-zero on any failure. Wire into the builder, not into a review checklist.
"""
